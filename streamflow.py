import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# Code Block 2: Calculate and Portray Shear & Moment Diagrams
# Define the variables
L = 6         # feet
R_a = 170     # pounds
R_b = 410     # pounds
P1 = 100      # pounds
q1 = 120      # pounds per foot
q2 = 120      # pounds per foot

x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# Update the V values according to their associated x values
for item in range(len(x)):
  x_val = x[item]                   # AI included this to keep track of every x value; this will then call the V value in the same position as the x value
  if x_val < 2:
    V[item] = R_a - (q1 * x_val)
  elif x_val >= 2 and x_val < 4:
    V[item] = R_a - (q1 * 2) - P1
  else:
    V[item] = R_a - (q1 * 2) - P1 + R_b - (q2 * (x_val - 4))

# Plot the graph
plt.plot(x, V, color="teal", alpha=0.8)
plt.title("Shear Diagram")
plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.axhline(y=0, color="black", linewidth=1)    # AI: the code axhline creates a horizontal line where y=0
plt.fill_between(x, V, alpha=0.5)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Code Block 3: Calculate and Portray the Moment Diagram
# Define the variables
L = 6         # feet
R_a = 170     # pounds
R_b = 410     # pounds
P1 = 100      # pounds
q1 = 120      # pounds per foot
q2 = 120      # pounds per foot

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Update the M values according to their associated x values
for item in range(len(x)):
  x_value = x[item]
  if x_value < 2:
    M[item] = (R_a * x_value) - (q1 * (x_value**2 / 2))
  elif x_value > 2 and x_value < 4:
    M[item] = (R_a * x_value) - (q1 * 2 * (x_value - 1)) - (P1 * (x_value - 2))
  else:
    M[item] = (R_a * x_value) - (q1 * 2 * (x_value - 1)) - (P1 * (x_value - 2)) + (R_b * (x_value - 4)) - (q2 * (x_value - 4) * ((x_value - 4) / 2))

# Plot the graph
plt.plot(x, M, color="teal")
plt.title("Moment Diagram")
plt.xlabel("x (ft)")
plt.ylabel("M (lb-ft)")
plt.axhline(y=0, color="black", linewidth=1)    # AI: the code axhline creates a horizontal line where y=0
plt.fill_between(x, M, alpha=0.5)
plt.show()

